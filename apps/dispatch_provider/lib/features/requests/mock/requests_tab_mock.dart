  static List<RequestModel> all() =>
      seed().where((r) => r.isAcceptable).toList();

  static List<RequestModel> nearby() =>
      seed().where((r) => r.isAcceptable && r.distanceKm < 5.0).toList();

  static List<RequestModel> assignments() => seed()
      .where((r) => r.isAcceptable && r.source == RequestSource.assignment)
      .toList();

  static List<RequestModel> commerce() => seed()
      .where((r) => r.isAcceptable && r.source == RequestSource.commerce)
      .toList();

  static RequestModel? byId(String id) {
    for (final r in seed()) {
      if (r.id == id) return r;
    }
    return null;
  }
