-- Apply once to the PostgreSQL database referenced by DATABASE_URL.
-- Safe to repeat if the table and index already exist.
-- If older data contain duplicate (email, segment) pairs, resolve those
-- duplicates explicitly before applying the unique index.
BEGIN;

CREATE TABLE IF NOT EXISTS public.waitlist (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  segment TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT waitlist_segment_check CHECK (
    segment IN ('customer', 'provider', 'vendor', 'fleet', 'api')
  )
);

-- Required by ON CONFLICT (email, segment) in the public waitlist endpoint.
CREATE UNIQUE INDEX IF NOT EXISTS waitlist_email_segment_unique_idx
  ON public.waitlist (email, segment);

COMMIT;
