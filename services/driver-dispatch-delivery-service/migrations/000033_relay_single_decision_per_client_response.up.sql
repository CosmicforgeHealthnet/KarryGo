-- Section 11: one provider clientResponseId is ONE decision.
--
-- 000032 made (operation_type, idempotency_key) unique, which lets the same
-- clientResponseId create a PROVIDER_*_ACCEPT row AND a PROVIDER_*_DECLINE
-- row — one provider response id representing two contradictory decisions.
-- Application-level check-then-insert closes the sequential case but not the
-- concurrent one: two transactions can both read "no conflict" before either
-- inserts. The database has to be the arbiter.
--
-- The namespace is (provider_id, idempotency_key), NOT idempotency_key alone.
-- clientResponseId is generated by a provider's own device and is only
-- meaningful within that provider; two providers independently choosing the
-- same client id is an ordinary collision, not a contradiction, and must not
-- make one provider's decision block another's.
--
-- Scoping it in the index rather than by prefixing the provider id into the
-- key keeps the invariant true regardless of how any future call site chooses
-- to construct that key.
CREATE UNIQUE INDEX IF NOT EXISTS uq_dispatch_relay_single_decision
    ON dispatch_fleet_relay_operations (provider_id, idempotency_key);

-- 000032's uq_dispatch_relay_idempotency (operation_type, idempotency_key) is
-- now both redundant and WRONG: it is global across providers, so two
-- providers independently choosing the same clientResponseId would collide and
-- the second provider's decision would be silently absorbed by the
-- ON CONFLICT DO NOTHING insert. The provider-scoped index above subsumes it —
-- one decision per provider per key, regardless of operation type.
DROP INDEX IF EXISTS uq_dispatch_relay_idempotency;
