package production

import (
	"encoding/base64"
	"encoding/json"
	"errors"
	"strings"
	"time"
)

var errInvalidQueueCursor = errors.New("invalid production queue cursor")

func encodeQueueCursor(item QueueItem) string {
	cursor := QueueCursorEnvelope{
		PromisedReadyAt: item.PromisedReadyAt,
		PriorityRank:    QueuePriorityRank(item.Priority),
		CreatedAt:       item.CreatedAt,
		ID:              item.ID,
	}
	raw, _ := json.Marshal(cursor)
	return base64.RawURLEncoding.EncodeToString(raw)
}

func decodeQueueCursor(raw string) (QueueCursorEnvelope, error) {
	raw = strings.TrimSpace(raw)
	if raw == "" || len(raw) > 1024 {
		return QueueCursorEnvelope{}, errInvalidQueueCursor
	}
	decoded, err := base64.RawURLEncoding.DecodeString(raw)
	if err != nil {
		return QueueCursorEnvelope{}, errInvalidQueueCursor
	}
	var cursor QueueCursorEnvelope
	if json.Unmarshal(decoded, &cursor) != nil || strings.TrimSpace(cursor.ID) == "" || cursor.CreatedAt.IsZero() || cursor.PriorityRank < 0 || cursor.PriorityRank > 2 {
		return QueueCursorEnvelope{}, errInvalidQueueCursor
	}
	if cursor.PromisedReadyAt != nil && cursor.PromisedReadyAt.IsZero() {
		return QueueCursorEnvelope{}, errInvalidQueueCursor
	}
	// Cursors generated by this service always use UTC timestamps. Rejecting
	// pathological values keeps an arbitrary decoded cursor from becoming an
	// unbounded or surprising query input.
	if cursor.CreatedAt.After(time.Now().UTC().Add(24 * time.Hour)) {
		return QueueCursorEnvelope{}, errInvalidQueueCursor
	}
	return cursor, nil
}
